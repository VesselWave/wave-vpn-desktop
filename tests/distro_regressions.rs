// B-22: plain resolv.conf under NetworkManager. The tunnel resolver is
// written again whenever another program replaced it, and Recover never
// wedges on a file someone else wrote: it keeps that newer file.
#[test]
fn forum_u2404_b22_foreign_resolv_conf_is_reasserted() {
    use wave_protocol::resolver::{needs_reassert, tunnel_resolv_conf, Current};
    let ours = tunnel_resolv_conf(&["10.128.0.1".into(), "fd7d:76ee:e68f:a993::1".into()]);
    assert!(ours.contains("nameserver 10.128.0.1\n"));
    assert!(ours.contains("nameserver fd7d:76ee:e68f:a993::1\n"));
    assert!(!needs_reassert(&Current::File(ours.clone()), &ours));
    let nm = "# Generated by NetworkManager\nsearch lan\nnameserver 192.168.1.1\n";
    assert!(needs_reassert(&Current::File(nm.into()), &ours));
    assert!(needs_reassert(&Current::Missing, &ours));
    assert!(needs_reassert(&Current::Other, &ours));
}

#[test]
fn forum_u2404_b22_recover_keeps_a_resolver_changed_outside_wave() {
    use wave_protocol::resolver::{restore, tunnel_resolv_conf, Current, Restore};
    let ours = tunnel_resolv_conf(&["10.128.0.1".into()]);
    let nm = Current::File("# Generated by NetworkManager\nnameserver 192.168.1.1\n".into());
    // Unchanged or missing: the original comes back.
    assert_eq!(
        restore(true, &Current::File(ours.clone()), Some(&ours)),
        Restore::Original
    );
    assert_eq!(
        restore(true, &Current::Missing, Some(&ours)),
        Restore::Original
    );
    // Rewritten by NetworkManager (or a symlink put back): keep it, drop the
    // backup, and report success instead of "Resolver changed outside Wave".
    assert_eq!(restore(true, &nm, Some(&ours)), Restore::KeepCurrent);
    assert_eq!(
        restore(true, &Current::Other, Some(&ours)),
        Restore::KeepCurrent
    );
    // An orphaned backup without a recovery record is resolved by the marker.
    assert_eq!(
        restore(true, &Current::File(ours.clone()), None),
        Restore::Original
    );
    assert_eq!(restore(true, &nm, None), Restore::KeepCurrent);
    assert_eq!(restore(false, &nm, Some(&ours)), Restore::Nothing);
}

#[test]
fn forum_u2404_b22_networkmanager_leaves_resolv_conf_alone_during_a_session() {
    use wave_protocol::resolver::{NM_DROP_IN, NM_DROP_IN_TEXT};
    assert!(NM_DROP_IN.starts_with("/run/NetworkManager/conf.d/"));
    assert!(NM_DROP_IN.ends_with(".conf"));
    assert!(NM_DROP_IN_TEXT.contains("[main]\ndns=none\n"));
    // The worker writes the drop-in and keeps resolv.conf asserted in its
    // monitor loop; cleanup removes the drop-in and reloads NetworkManager.
    let source = include_str!("../src/platform/linux.rs");
    for needle in [
        "resolver::NM_DROP_IN",
        "fn reassert_resolver",
        "fn release_networkmanager",
        "resolver::restore(",
    ] {
        assert!(source.contains(needle), "{needle}");
    }
}

#[test]
fn forum_u2404_b22_repeated_rewrites_warn_once_per_minute() {
    use std::time::{Duration, Instant};
    let mut r = wave_protocol::resolver::Reasserts::default();
    let t = Instant::now();
    assert!(r.warn(t));
    assert!(!r.warn(t + Duration::from_secs(5)));
    assert!(r.warn(t + Duration::from_secs(61)));
    assert_eq!(r.count, 3);
}

// B-14: only a lock Wave applied last and that is now gone counts as lost;
// a cached file alone never claims protection either way.
#[test]
fn forum_u2404_b14_lock_loss_needs_wave_state_and_a_missing_table() {
    use wave_protocol::protection::lock_lost;
    assert!(lock_lost(Some(true), Some(false)));
    assert!(!lock_lost(Some(true), Some(true)));
    assert!(!lock_lost(Some(false), Some(false)));
    assert!(!lock_lost(None, Some(false)));
    assert!(!lock_lost(Some(true), None));
    let source = include_str!("../src/platform/linux.rs");
    for needle in [
        "fn restore_lost_firewall",
        "protection::lock_lost(",
        "\"lock_lost\"",
    ] {
        assert!(source.contains(needle), "{needle}");
    }
}

