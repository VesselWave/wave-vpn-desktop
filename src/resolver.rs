//! Decisions for the plain `/etc/resolv.conf` DNS backend (no systemd-resolved,
//! no resolvconf), kept free of I/O so they are tested on every platform.
//!
//! Like Eddie 2.27.2 (`App.CLI.Linux.Elevated/src/impl.cpp` "dns-switch-do",
//! re-run by `Lib.Platform.Linux/Platform.cs` `OnCheckUpMonitor`), the worker
//! re-checks the file while connected and writes the tunnel resolver again
//! when another program replaced it. In addition, while a session runs,
//! NetworkManager is told not to touch resolv.conf at all through a runtime
//! drop-in, so its rewrites on reconnects and restarts never happen.
//! Recovery never wedges: a file another program wrote after Wave's is kept.

/// The original file while a session owns `/etc/resolv.conf`.
pub const BACKUP: &str = "/etc/resolv.conf.wave-vpn-backup";
/// Runtime NetworkManager drop-in (tmpfs: gone after reboot). NetworkManager
/// reads conf.d files in name order across /usr/lib, /run and /etc, later
/// ones overriding earlier ones, so the name sorts after typical admin files.
pub const NM_DROP_IN: &str = "/run/NetworkManager/conf.d/zz-wave-vpn-dns.conf";
pub const NM_DROP_IN_TEXT: &str = "# Wave VPN: the tunnel owns /etc/resolv.conf during this session.\n# Removed on Disconnect or Recover.\n[main]\ndns=none\n";
/// First line of every resolv.conf Wave writes, so an orphaned backup can
/// be resolved even without a recovery record.
pub const MARKER: &str = "# Generated by Wave VPN for the tunnel.";

pub fn tunnel_resolv_conf(dns: &[String]) -> String {
    let mut text = format!("{MARKER} The original is {BACKUP}.\n");
    for ip in dns {
        text.push_str(&format!("nameserver {ip}\n"));
    }
    text
}

/// What is at `/etc/resolv.conf` now.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Current {
    Missing,
    /// A regular file with this content.
    File(String),
    /// A symlink, unreadable file or anything that is not a regular file.
    Other,
}

/// Monitor: write the tunnel resolver again unless it is already in effect.
pub fn needs_reassert(current: &Current, expected: &str) -> bool {
    !matches!(current, Current::File(text) if text == expected)
}

/// What cleanup does with the backup.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Restore {
    /// No backup: nothing to undo.
    Nothing,
    /// The current file is Wave's (or missing): put the original back.
    Original,
    /// Another program wrote the current file after Wave did (a resolver
    /// manager, DHCP client or the user): it is newer than the original, so
    /// keep it and drop the backup instead of blocking Recover.
    KeepCurrent,
}

/// `recorded` is the content Wave wrote, from the recovery record; without a
/// record (orphaned backup) Wave's own marker identifies its file.
pub fn restore(backup_exists: bool, current: &Current, recorded: Option<&str>) -> Restore {
    if !backup_exists {
        return Restore::Nothing;
    }
    match current {
        Current::Missing => Restore::Original,
        Current::File(text) if recorded == Some(text.as_str()) || text.starts_with(MARKER) => {
            Restore::Original
        }
        _ => Restore::KeepCurrent,
    }
}

/// Rate limit for the "replaced by another program" warning: the first one,
/// then one per minute of repeated rewrites.
#[derive(Default)]
pub struct Reasserts {
    pub count: u64,
    last_warned: Option<std::time::Instant>,
}
impl Reasserts {
    pub fn warn(&mut self, now: std::time::Instant) -> bool {
        self.count += 1;
        let due = self
            .last_warned
            .is_none_or(|t| now.duration_since(t) >= std::time::Duration::from_secs(60));
        if due {
            self.last_warned = Some(now);
        }
        due
    }
}
